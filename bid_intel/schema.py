"""Extraction schema: what to pull from a bid, the query used to retrieve it, and the rule that
matches the value. Each rule uses a named group 'value' unless the field has a fixed static value."""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class FieldSpec:
    key: str
    label: str
    query: str
    pattern: str
    static: str | None = None

    @property
    def regex(self) -> re.Pattern:
        return re.compile(self.pattern, re.IGNORECASE)


